-- Suivi de commande : historique des étapes et position du colis, par boutique.
CREATE TABLE order_events (
  id         BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  order_id   CHAR(26) NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  shop_id    CHAR(26) REFERENCES shops(id),
  kind       VARCHAR(10) NOT NULL CHECK (kind IN ('placed','confirmed','shipped','delivered','cancelled','update')),
  location   VARCHAR(120),
  note       VARCHAR(300),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);
CREATE INDEX order_events_order ON order_events(order_id, id);

-- Commandes existantes : on reconstitue l'étape de départ et l'étape actuelle.
INSERT INTO order_events(order_id, kind, location, note, created_at)
  SELECT id, 'placed', shipping_city, 'Commande passée', created_at FROM orders;
INSERT INTO order_events(order_id, kind, note, created_at)
  SELECT id, status, CASE status WHEN 'confirmed' THEN 'Commande confirmée par le vendeur' WHEN 'shipped' THEN 'Colis expédié' WHEN 'delivered' THEN 'Colis livré' ELSE 'Commande annulée' END, created_at
    FROM orders WHERE status <> 'pending';
