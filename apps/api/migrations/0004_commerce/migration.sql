-- Boutiques, produits (jusqu'à 5 photos), adresses, commandes.
CREATE TABLE shops (
  id           CHAR(26) PRIMARY KEY,
  owner_id     CHAR(26) UNIQUE REFERENCES users(id),      -- NULL pour la boutique officielle
  name         VARCHAR(100) NOT NULL,
  slug         VARCHAR(120) NOT NULL UNIQUE,
  city_id      CHAR(26) REFERENCES cities(id),
  phone        VARCHAR(16),
  description  TEXT,
  plan         VARCHAR(20) NOT NULL DEFAULT 'free',
  is_official  BOOLEAN NOT NULL DEFAULT false,
  status       VARCHAR(12) NOT NULL DEFAULT 'active' CHECK (status IN ('pending','active','suspended')),
  created_at   TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);

CREATE TABLE products (
  id                 BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  shop_id            CHAR(26) NOT NULL REFERENCES shops(id),
  name               VARCHAR(200) NOT NULL,
  description        TEXT NOT NULL DEFAULT '',
  price_usd          NUMERIC(12,2) NOT NULL CHECK (price_usd > 0),
  original_price_usd NUMERIC(12,2) CHECK (original_price_usd IS NULL OR original_price_usd > price_usd),
  department         VARCHAR(30) NOT NULL,
  category           VARCHAR(80) NOT NULL,
  sku                VARCHAR(40),
  colors             TEXT[] NOT NULL DEFAULT '{}',
  sizes              TEXT[] NOT NULL DEFAULT '{}',
  tags               TEXT[] NOT NULL DEFAULT '{}',
  in_stock           BOOLEAN NOT NULL DEFAULT true,
  status             VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active','archived')),
  created_at         TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);
CREATE INDEX products_shop_idx ON products(shop_id);

CREATE TABLE product_images (
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  position   SMALLINT NOT NULL CHECK (position BETWEEN 0 AND 4),   -- 5 photos maximum
  url        TEXT NOT NULL,
  PRIMARY KEY (product_id, position)
);

CREATE TABLE customer_addresses (
  id         CHAR(26) PRIMARY KEY,
  user_id    CHAR(26) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label      VARCHAR(60) NOT NULL DEFAULT 'Adresse',
  city       VARCHAR(80) NOT NULL,
  address    TEXT NOT NULL,
  phone      VARCHAR(16) NOT NULL CHECK (phone ~ '^\+[1-9][0-9]{6,14}$'),
  is_default BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);
CREATE INDEX customer_addresses_user_idx ON customer_addresses(user_id);

CREATE SEQUENCE order_number_seq START 1001;
CREATE TABLE orders (
  id               CHAR(26) PRIMARY KEY,
  number           VARCHAR(20) NOT NULL UNIQUE,
  user_id          CHAR(26) NOT NULL REFERENCES users(id),
  status           VARCHAR(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','shipped','delivered','cancelled')),
  payment_method   VARCHAR(12) NOT NULL DEFAULT 'cod',
  subtotal_usd     NUMERIC(12,2) NOT NULL,
  shipping_phone   VARCHAR(16) NOT NULL,
  shipping_city    VARCHAR(80) NOT NULL,
  shipping_address TEXT NOT NULL,
  created_at       TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);
CREATE INDEX orders_user_idx ON orders(user_id, created_at DESC);

CREATE TABLE order_items (
  id             CHAR(26) PRIMARY KEY,
  order_id       CHAR(26) NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id     BIGINT NOT NULL REFERENCES products(id),
  shop_id        CHAR(26) NOT NULL REFERENCES shops(id),
  name           VARCHAR(200) NOT NULL,   -- copie au moment de l'achat
  unit_price_usd NUMERIC(12,2) NOT NULL,  -- prix relu en base, jamais celui du navigateur
  quantity       INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 100),
  color          VARCHAR(60) NOT NULL DEFAULT '',
  size           VARCHAR(60) NOT NULL DEFAULT '',
  image          TEXT
);
CREATE INDEX order_items_order_idx ON order_items(order_id);
CREATE INDEX order_items_shop_idx ON order_items(shop_id);
