-- Messagerie acheteur ↔ vendeur, notifications d'administration, validation des boutiques, taux de change.

-- Une boutique peut maintenant être refusée par l'administrateur (motif facultatif).
ALTER TABLE shops DROP CONSTRAINT IF EXISTS shops_status_check;
ALTER TABLE shops ADD CONSTRAINT shops_status_check CHECK (status IN ('pending','active','suspended','rejected'));
ALTER TABLE shops ADD COLUMN reject_reason TEXT;

-- Notifications pour l'équipe d'administration (nouvelle boutique, etc.).
CREATE TABLE notifications (
  id         BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  kind       VARCHAR(40) NOT NULL,
  title      VARCHAR(200) NOT NULL,
  body       TEXT,
  ref        VARCHAR(40),
  read       BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);
CREATE INDEX notifications_unread ON notifications(read, created_at DESC);

-- Discussions : une par couple (acheteur, boutique), les messages peuvent citer un produit.
CREATE TABLE conversations (
  id              BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  buyer_id        CHAR(26) NOT NULL REFERENCES users(id),
  shop_id         CHAR(26) NOT NULL REFERENCES shops(id),
  last_message_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  buyer_read_at   TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  shop_read_at    TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  created_at      TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  UNIQUE (buyer_id, shop_id)
);
CREATE INDEX conversations_shop ON conversations(shop_id, last_message_at DESC);

CREATE TABLE messages (
  id              BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  sender          VARCHAR(6) NOT NULL CHECK (sender IN ('buyer','seller')),
  body            TEXT NOT NULL,
  product_id      BIGINT REFERENCES products(id),
  created_at      TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);
CREATE INDEX messages_conv ON messages(conversation_id, id);

-- Taux de change : unités de monnaie locale pour 1 USD, rafraîchis depuis une source externe.
CREATE TABLE exchange_rates (
  code       VARCHAR(3) PRIMARY KEY,
  rate       NUMERIC(18,6) NOT NULL CHECK (rate > 0),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);
